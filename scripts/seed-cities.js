function uniqueTitles(titles) {
  const seen = new Set();
  const result = [];

  for (const title of titles) {
    if (seen.has(title)) continue;
    seen.add(title);
    result.push(title);
  }

  return result;
}

async function main() {
  const { createStrapi, compileStrapi } = require('@strapi/strapi');
  const titles = uniqueTitles(TITLES);

  const appContext = await compileStrapi();
  const app = await createStrapi(appContext).load();
  app.log.level = 'error';

  try {
    const existing = await strapi.db.query('api::city.city').findMany({
      select: ['title', 'slug'],
    });
    const existingTitles = new Set(existing.map((item) => item.title));
    const existingSlugs = new Set(existing.map((item) => item.slug).filter(Boolean));

    const pending = [];
    let skipped = 0;

    for (const title of titles) {
      if (existingTitles.has(title)) {
        skipped += 1;
        continue;
      }

      const baseSlug = slugify(title);
      if (!baseSlug) {
        throw new Error(`Empty slug for "${title}"`);
      }

      let slug = baseSlug;
      let suffix = 2;
      while (existingSlugs.has(slug)) {
        slug = `${baseSlug}-${suffix}`;
        suffix += 1;
      }

      existingTitles.add(title);
      existingSlugs.add(slug);
      pending.push({ title, slug });
    }

    let created = 0;
    const concurrency = 8;

    for (let index = 0; index < pending.length; index += concurrency) {
      const batch = pending.slice(index, index + concurrency);
      await Promise.all(
        batch.map((entry) =>
          strapi.documents('api::city.city').create({
            data: entry,
            status: 'published',
          })
        )
      );
      created += batch.length;
      console.log(`created ${created}/${pending.length}`);
    }

    const published = await strapi.documents('api::city.city').findMany({
      status: 'published',
      fields: ['title'],
      limit: 1000,
    });

    console.log(
      JSON.stringify({
        requested: titles.length,
        created,
        skipped,
        published: published.length,
      })
    );
  } finally {
    await app.destroy();
  }
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
